/**
 * SF Symbols used by the Cash reconciliation navigation drawer.
 *
 * The outlines are the real thing, not approximations: extracted from
 * `SF Symbols.app/Contents/Resources/Fonts/SFSymbolsFallback.otf` at the `.medium` optical
 * size (the weight the design uses), by looking up each symbol's private-use codepoint in the
 * font's cmap and converting the glyph to a path. Each symbol's codepoint is recorded below so
 * the extraction is reproducible — re-run it against a newer SF Symbols release to update.
 *
 * SF Symbols are filled paths shaped to read as strokes, so these use `fill: currentColor` and
 * carry the font's own viewBox rather than the 24x24 / 1.5px-stroke convention in
 * `components/ios/IosIcons.tsx`. They stay here rather than in that shared file because nothing
 * on Trunk uses them; promote one the moment a Trunk screen does.
 */
interface IconProps extends Omit<SVGProps<SVGSVGElement>, 'width' | 'height'> {
  size?: string;
  style?: CSSProperties;
}

function base(size: string | undefined) {
  return {
    width: size ?? 'var(--icon-medium)',
    height: size ?? 'var(--icon-medium)',
    fill: 'none',
    'aria-hidden': true,
  } as const;
}

